import assert from 'node:assert/strict';
import {test} from 'node:test';
import {client,registerCustomer} from './helpers.mjs';
test('identity, recovery, KYC resubmission, settings and administrative access persist',async()=>{
 const {session,credentials,data}=await registerCustomer('identity');
 assert.equal((await session.get('auth/me')).data.user.id,data.user.id);
 await session.get('admin/kyc',403);
 const change=await session.put('profile',{salary:8000001,essential:2200000,existing_emi:400000});
 assert.equal(change.data.metrics.disposable,5400001);
 await session.put('profile',{salary:-1},422);
 assert.equal((await session.get('profile')).data.profile.salary,8000001);
 const proof={name:'sample.txt',mime:'text/plain',content_base64:Buffer.from('CREDWISE-SYNTHETIC local training document').toString('base64')};
 const kyc={legal_name:credentials.name,address:'Example Street 5',employment:'Salaried',pan:'DEMOX0217Q',document:proof};
 await session.post('kyc',{...kyc,pan:'INVALID'},422);
 assert.equal((await session.post('kyc',kyc,201)).data.kyc.status,'pending');
 const admin=client();await admin.post('auth/login',{email:'admin@credwise.test',password:'CredWiseDemo!360'});
 const path='admin/kyc/'+data.user.id;
 assert.equal((await admin.get(path+'/document')).data.content_base64,proof.content_base64);
 await admin.post(path,{status:'rejected',reason:'Use the revised synthetic fixture.'});
 assert.equal((await session.get('kyc')).data.kyc.status,'rejected');
 await session.post('kyc',kyc,201);
 await admin.post(path,{status:'verified',reason:'Synthetic evidence reviewed.'});
 assert.equal((await session.get('kyc')).data.kyc.status,'verified');
 await session.put('settings',{preferences:{language:'hi',notifications:{payments:false}}});
 assert.equal((await session.get('settings')).data.preferences.notifications.payments,false);
 const fresh=client(),new_password=credentials.password+'-rotated';
 const reset=await fresh.post('auth/recover',{email:credentials.email,recovery_code:data.recovery_code,new_password});
 assert.notEqual(reset.data.recovery_code,data.recovery_code);
 await session.get('auth/me',401);
 await fresh.post('auth/login',{email:credentials.email,password:new_password});
 assert.equal((await fresh.get('profile')).data.profile.salary,8000001);
 await admin.post('admin/users/'+data.user.id,{active:false});
 await fresh.get('auth/me',401);
 await admin.post('admin/users/'+data.user.id,{active:true});
 await fresh.post('auth/login',{email:credentials.email,password:new_password});
 await fresh.post('auth/logout',{});
 await fresh.get('auth/me',401);
});
