CREATE TABLE product_policy_changes (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_slug text NOT NULL REFERENCES loan_products(slug),
    admin_id bigint NOT NULL REFERENCES users(id),
    previous_policy jsonb NOT NULL,
    policy jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX product_policy_history_idx ON product_policy_changes(product_slug, id DESC);
