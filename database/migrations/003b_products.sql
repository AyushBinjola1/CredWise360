CREATE TABLE loan_products (
    slug text PRIMARY KEY,
    display_order smallint NOT NULL UNIQUE,
    name text NOT NULL,
    description text NOT NULL,
    purposes text[] NOT NULL CHECK (cardinality(purposes) > 0),
    documents text[] NOT NULL CHECK (cardinality(documents) > 0),
    collateral text NOT NULL,
    min_amount bigint NOT NULL CHECK (min_amount > 0),
    max_amount bigint NOT NULL CHECK (max_amount BETWEEN min_amount AND 100000000000),
    min_months integer NOT NULL CHECK (min_months >= 1),
    max_months integer NOT NULL CHECK (max_months BETWEEN min_months AND 600),
    rate_bps integer NOT NULL CHECK (rate_bps BETWEEN 0 AND 6000),
    fee_bps integer NOT NULL CHECK (fee_bps BETWEEN 0 AND 5000),
    fee_cap bigint NOT NULL DEFAULT 0 CHECK (fee_cap BETWEEN 0 AND 100000000000),
    method text NOT NULL CHECK (method IN ('reducing','flat')),
    min_income bigint NOT NULL CHECK (min_income BETWEEN 0 AND 100000000000),
    max_emi_percent integer NOT NULL CHECK (max_emi_percent BETWEEN 1 AND 100),
    min_score integer NOT NULL CHECK (min_score BETWEEN 300 AND 900),
    min_stability_months integer NOT NULL CHECK (min_stability_months BETWEEN 0 AND 1200),
    prepayment_from_month integer NOT NULL CHECK (prepayment_from_month BETWEEN 1 AND 600),
    prepayment_fee_bps integer NOT NULL CHECK (prepayment_fee_bps BETWEEN 0 AND 5000),
    late_fee bigint NOT NULL CHECK (late_fee BETWEEN 0 AND 100000000000),
    grace_days integer NOT NULL CHECK (grace_days BETWEEN 0 AND 180),
    risk_policy text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

